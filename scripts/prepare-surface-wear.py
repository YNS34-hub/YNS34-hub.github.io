"""原创线性材质数据，不修改收藏图片，不下载或烘焙视频画面。"""
import random
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter, ImageChops

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public/media/realism"
OUT.mkdir(parents=True, exist_ok=True)
W, H = 1024, 1536  # 24 x 36 m，裂纹在双倍分辨率生成后抗锯齿缩小。
rng = random.Random(431960)

def noise(cols, rows, lo, hi):
    im = Image.new("L", (cols, rows))
    im.putdata([rng.randint(lo, hi) for _ in range(cols * rows)])
    return im.resize((W, H), Image.Resampling.BICUBIC)

albedo = Image.blend(noise(9, 13, 104, 174), noise(69, 103, 118, 160), .26)
roughness = Image.blend(noise(17, 25, 199, 247), noise(163, 241, 218, 249), .28)
cracks = Image.new("L", (W * 2, H * 2)); draw = ImageDraw.Draw(cracks)
for _ in range(20):
    x, y = rng.uniform(0, W * 2), rng.uniform(0, H * 2)
    pts = [(x, y)]
    angle = rng.uniform(-2, 2)
    for _ in range(rng.randint(5, 13)):
        x += rng.uniform(-9, 9) + angle * 4; y += rng.uniform(7, 20)
        pts.append((x, y))
    draw.line(pts, fill=rng.randint(95, 190), width=1)
cracks = cracks.resize((W, H), Image.Resampling.LANCZOS)

# 半场附近薄涂层的使用痕迹，仅影响反射粗糙度，不改变画线、标记和原涂装。
polish = Image.new("L", (W, H)); brush = ImageDraw.Draw(polish)
for end in [.18, .82]:
    for _ in range(25):
        x, y = rng.gauss(W * .5, W * .105), rng.gauss(H * end, H * .045)
        rx, ry = rng.uniform(3, 13), rng.uniform(2, 8)
        brush.ellipse((x-rx, y-ry, x+rx, y+ry), fill=rng.randint(15, 40))
roughness = ImageChops.subtract(roughness, polish.filter(ImageFilter.GaussianBlur(3)))
Image.merge("RGB", (albedo, roughness, cracks)).save(OUT / "court-wear.webp", lossless=True, method=6)
(OUT / "SOURCES.md").write_text("""# Material data\n\n`court-wear.webp` is original deterministic material data generated by\n`scripts/prepare-surface-wear.py` (seed 431960), not a photograph or a video frame.\nIt maps once to the existing 24 x 36 metre court. R = restrained coating variation;\nG = dry surface roughness / foot-contact polish; B = sparse antialiased hairline wear.\nAll channels are linear data (`NoColorSpace`); the existing court artwork is retained.\nNo commercial logos, audio or private media are included.\n""", encoding="utf-8")
print(OUT / "court-wear.webp")
